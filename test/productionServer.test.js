/**
 * test/productionServer.test.js
 *
 * Live HTTP smoke tests for Phase 4.3 Production Frontend & Backend Integration.
 * Starts the Express server in NODE_ENV=production and verifies:
 *  1. GET / returns actual React application HTML.
 *  2. Frontend JS & CSS static assets load with HTTP 200.
 *  3. GET /api/health returns 200 with service metadata and no leaked credentials.
 *  4. POST /api/rules/interpret remains fully accessible.
 *  5. Unknown GET /api/unknown endpoint returns JSON 404 (not HTML).
 *  6. Refreshing frontend routes (GET /cart, GET /checkout) returns index.html.
 *  7. Natural language discount rule interpretation endpoint works.
 *  8. Frontend compiled bundle in dist/ does not contain any LLM API credentials.
 */

import { describe, it, before, after } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { app, DIST_DIR, INDEX_HTML } from '../server/index.js'

describe('Phase 4.3 — Production Frontend and Backend Integration', () => {
  let server
  let baseUrl
  const originalEnv = process.env.NODE_ENV

  before(async () => {
    process.env.NODE_ENV = 'production'
    server = app.listen(0)
    await new Promise((resolve) => server.once('listening', resolve))
    const port = server.address().port
    baseUrl = `http://localhost:${port}`
  })

  after(async () => {
    process.env.NODE_ENV = originalEnv
    if (server) {
      await new Promise((resolve) => server.close(resolve))
    }
  })

  it('Check 1: GET / returns the actual React application HTML from dist/', async () => {
    const res = await fetch(`${baseUrl}/`)
    assert.equal(res.status, 200)
    assert.match(res.headers.get('content-type') || '', /text\/html/)
    const html = await res.text()
    assert.ok(html.includes('<div id="root"></div>') || html.includes('id="root"'))
    assert.ok(!html.includes('Opptra Discount Engine — Development API Gateway'))
  })

  it('Check 2: Frontend JavaScript and CSS assets load successfully with HTTP 200', async () => {
    // Read the compiled index.html to find the actual asset paths generated by Vite
    const indexHtml = fs.readFileSync(INDEX_HTML, 'utf8')
    const jsMatch = indexHtml.match(/src="(\/assets\/[^"]+\.js)"/)
    const cssMatch = indexHtml.match(/href="(\/assets\/[^"]+\.css)"/)

    assert.ok(jsMatch, 'Compiled JS asset must be referenced in index.html')
    const jsPath = jsMatch[1]
    const jsRes = await fetch(`${baseUrl}${jsPath}`)
    assert.equal(jsRes.status, 200)
    assert.match(jsRes.headers.get('content-type') || '', /javascript/)

    if (cssMatch) {
      const cssPath = cssMatch[1]
      const cssRes = await fetch(`${baseUrl}${cssPath}`)
      assert.equal(cssRes.status, 200)
      assert.match(cssRes.headers.get('content-type') || '', /css/)
    }
  })

  it('Check 3: GET /api/health returns 200 with service metadata and hasKey boolean', async () => {
    const res = await fetch(`${baseUrl}/api/health`)
    assert.equal(res.status, 200)
    const data = await res.json()
    assert.equal(data.status, 'ok')
    assert.equal(data.service, 'discount-engine-backend')
    assert.equal(typeof data.hasKey, 'boolean')
    // Guarantee no secret keys or environment variables are leaked
    assert.equal(data.GEMINI_API_KEY, undefined)
    assert.equal(data.OPENAI_API_KEY, undefined)
  })

  it('Check 4: POST /api/rules/interpret remains accessible and validates input', async () => {
    const res = await fetch(`${baseUrl}/api/rules/interpret`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ instruction: '   ' }), // invalid empty string
    })
    assert.equal(res.status, 400)
    const data = await res.json()
    assert.equal(data.status, 'error')
    assert.match(data.message, /non-empty "instruction" string/)
  })

  it('Check 5: Unknown /api/* route returns JSON 404 (never HTML fallback)', async () => {
    const res = await fetch(`${baseUrl}/api/nonexistent-endpoint-test`)
    assert.equal(res.status, 404)
    assert.match(res.headers.get('content-type') || '', /application\/json/)
    const data = await res.json()
    assert.equal(data.status, 'error')
    assert.match(data.message, /Route GET \/api\/nonexistent-endpoint-test not found/)
  })

  it('Check 6: Refreshing deep frontend routes (SPA fallback) returns index.html', async () => {
    const res = await fetch(`${baseUrl}/checkout/cart-review`)
    assert.equal(res.status, 200)
    assert.match(res.headers.get('content-type') || '', /text\/html/)
    const html = await res.text()
    assert.ok(html.includes('<div id="root"></div>') || html.includes('id="root"'))
  })

  it('Check 7: Interprets a natural language discount rule and returns valid rule schema', async () => {
    const res = await fetch(`${baseUrl}/api/rules/interpret`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ instruction: 'Give 15% off on all Natura Casa products' }),
    })

    assert.equal(res.status, 200)
    const data = await res.json()
    assert.equal(data.status, 'success')
    assert.ok(data.rule, 'Response must contain a rule object')
    assert.equal(data.rule.scope, 'brand')
    assert.equal(data.rule.appliesTo, 'Natura Casa')
    assert.equal(data.rule.type, 'percentage')
    assert.equal(data.rule.value, 15)
    assert.equal(data.rule.stackable, false)
  })

  it('Check 8: Frontend production bundle does not contain any secret LLM API keys', () => {
    // Scan all built JS files in dist/assets
    const assetsDir = path.join(DIST_DIR, 'assets')
    const files = fs.readdirSync(assetsDir).filter((f) => f.endsWith('.js'))

    for (const f of files) {
      const content = fs.readFileSync(path.join(assetsDir, f), 'utf8')
      // Ensure raw API keys or private keys are not bundled in frontend client code
      if (process.env.GEMINI_API_KEY) {
        assert.ok(
          !content.includes(process.env.GEMINI_API_KEY),
          `Bundle file ${f} must not leak GEMINI_API_KEY`
        )
      }
      if (process.env.OPENAI_API_KEY) {
        assert.ok(
          !content.includes(process.env.OPENAI_API_KEY),
          `Bundle file ${f} must not leak OPENAI_API_KEY`
        )
      }
    }
  })

  it('Check 9: Returns descriptive 500 error if production build is missing', async () => {
    // Temporarily point DIST_DIR to non-existent folder
    const originalDist = DIST_DIR
    // We can simulate request by calling a handler or mocking fs.existsSync
    const origExists = fs.existsSync
    try {
      fs.existsSync = (p) => {
        if (typeof p === 'string' && (p.includes('dist') || p.endsWith('dist'))) return false
        return origExists(p)
      }
      const res = await fetch(`${baseUrl}/some-page`)
      assert.equal(res.status, 500)
      const text = await res.text()
      assert.match(text, /Production build directory \(dist\/\) not found/)
    } finally {
      fs.existsSync = origExists
    }
  })
})
